"""Assemble the whole dataset into a single self-describing `dataset/` folder.

Collects the dimension tables, fact tables, ground-truth labels and the real
external inputs into one place with a clear layout:

    dataset/
      README.md            — overview & how to read (versioned)
      DATA_DICTIONARY.md   — field-by-field dictionary (versioned)
      MANIFEST.md          — auto-generated: tables, row counts, sizes
      dimensions/          — dim_* reference tables (+ CSV mirrors)
      facts/               — fact_transactions/ (partitioned), cash_ops, atm_status
      labels/              — anomaly ground truth (§7)
      external/            — real parsed inputs (weather, FX, OSM)

Files are hard-linked (no extra disk use) when possible, else copied. Re-run
after any rebuild to refresh the release folder:  python -m generator.export_dataset
"""

import logging
import os
import shutil
from pathlib import Path

import pyarrow.parquet as pq

from . import PROJECT_ROOT, load_config

log = logging.getLogger(__name__)

DIMS = ["dim_district", "dim_calendar", "dim_atm", "dim_customer", "dim_card"]
FACT_FILES = ["fact_cash_ops.parquet", "fact_atm_status.parquet"]


def _link(src: Path, dst: Path) -> None:
    """Hard-link src→dst (0 extra bytes); fall back to copy across filesystems."""
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists():
        dst.unlink()
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def export(config: dict) -> Path:
    data = PROJECT_ROOT / config["output"]["data_dir"]
    dst = PROJECT_ROOT / "dataset"

    # Dimensions (+ CSV mirrors where present).
    for t in DIMS:
        _link(data / f"{t}.parquet", dst / "dimensions" / f"{t}.parquet")
        csv = data / f"{t}.csv"
        if csv.exists():
            _link(csv, dst / "dimensions" / f"{t}.csv")

    # Facts: flat tables + partitioned fact_transactions tree.
    for f in FACT_FILES:
        _link(data / f, dst / "facts" / f)
    src_ft = data / "fact_transactions"
    for p in src_ft.rglob("*.parquet"):
        _link(p, dst / "facts" / "fact_transactions" / p.relative_to(src_ft))

    # Labels and external inputs (mirror whole folders).
    for sub in ("labels", "external"):
        s = PROJECT_ROOT / sub
        if s.exists():
            for p in s.rglob("*.parquet"):
                _link(p, dst / sub / p.relative_to(s))

    _write_manifest(dst)
    log.info("Dataset assembled → %s", dst)
    return dst


def _rows(path: Path) -> int:
    return pq.read_metadata(path).num_rows


def _dir_size(path: Path) -> int:
    return sum(p.stat().st_size for p in path.rglob("*") if p.is_file())


def _write_manifest(dst: Path) -> None:
    """Auto-generated inventory with live row counts and sizes."""
    lines = ["# MANIFEST — dataset contents", "",
             "> Auto-generated by `generator/export_dataset.py`. Edit README/DATA_DICTIONARY, not this file.",
             "", "| Table | Rows | File(s) |", "|---|---:|---|"]

    dims = dst / "dimensions"
    for t in DIMS:
        p = dims / f"{t}.parquet"
        if p.exists():
            lines.append(f"| `dimensions/{t}` | {_rows(p):,} | parquet"
                         f"{' + csv' if (dims/f'{t}.csv').exists() else ''} |")

    ft = dst / "facts" / "fact_transactions"
    if ft.exists():
        parts = list(ft.rglob("*.parquet"))
        total = sum(_rows(p) for p in parts)
        lines.append(f"| `facts/fact_transactions` | {total:,} | {len(parts)} partitions year=/month= |")
    for f in FACT_FILES:
        p = dst / "facts" / f
        if p.exists():
            lines.append(f"| `facts/{Path(f).stem}` | {_rows(p):,} | parquet |")

    for sub in ("labels", "external"):
        d = dst / sub
        if d.exists():
            for p in sorted(d.rglob("*.parquet")):
                lines.append(f"| `{sub}/{p.stem}` | {_rows(p):,} | parquet |")

    total_size = _dir_size(dst) / 1e6
    lines += ["", f"**Total size:** ~{total_size:,.0f} MB "
              f"(hard-linked to the working `data/`, no real disk duplication).", ""]
    (dst / "MANIFEST.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    export(load_config())


if __name__ == "__main__":
    main()
